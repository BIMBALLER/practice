// Solution

const name = "Alex";           // String
const age = 20;                // Number
let city = "New York";         // String
const isStudent = true;        // Boolean

// Template Literal
console.log(`Hello, my name is ${name}.`);
console.log(`I am ${age} years old and I live in ${city}.`);
console.log(`I am a student: ${isStudent}`);

// Using operators
const ageIn5Years = age + 5;
console.log(`My age in 5 years will be ${ageIn5Years}.`);

// Bonus: Total score example
let score = 85;
score += 10;   // using assignment operator

console.log(`My current score is ${score}`);